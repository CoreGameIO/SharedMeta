        private static void GenerateEntityRecorderMethod(StringBuilder sb, IMethodSymbol method, string interfaceName, string interfaceFqn, DetectedSerializer serializer)
        {
            var methodName = method.Name;
            var returnType = method.ReturnType.ToDisplayString();

            // Get method alias from MetaMethod attribute if available
            var methodAlias = methodName;
            var metaMethodAttr = method.GetAttributes().FirstOrDefault(a =>
                a.AttributeClass?.ToDisplayString() == "SharedMeta.Core.MetaMethodAttribute");
            if (metaMethodAttr != null)
            {
                var aliasArg = metaMethodAttr.NamedArguments.FirstOrDefault(a => a.Key == "Alias");
                if (!aliasArg.Value.IsNull && aliasArg.Value.Value is string alias && !string.IsNullOrEmpty(alias))
                {
                    methodAlias = alias;
                }
            }

            // Build parameter list
            var parameters = string.Join(", ", method.Parameters.Select(p => $"{p.Type.ToDisplayString()} {p.Name}"));
            var paramNames = method.Parameters.Select(p => p.Name).ToList();

            var (isAsync, innerType) = ParseReturnType(returnType);

            // 0.22.0+: OneWay variant — emit void method that packs args and fires
            // _context.CallEntityOneWay(...) without awaiting or recording any result.
            if (IsNotificationMode(method))
            {
                sb.AppendLine();
                sb.AppendLine($"        [global::SharedMeta.Core.GeneratedFromMetaMethod(typeof(global::{interfaceFqn}), \"{methodName}\")]");
                sb.AppendLine($"        public void {methodName}({parameters})");

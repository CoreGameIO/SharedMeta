                GenerateArgumentPacking(sb, method.Parameters, paramNames, serializer);
                sb.AppendLine();
                sb.AppendLine($"            _context.CallEntityOneWay(_entityId, \"{interfaceName}\", \"{methodAlias}\", argsBytes);");
                sb.AppendLine("        }");
                return;
            }

            // Determine async method signature
            string asyncReturnType;
            string asyncMethodName;

            if (isAsync)
            {
                asyncReturnType = returnType;
                asyncMethodName = methodName;
            }
            else if (returnType == "void")
            {
                asyncReturnType = "Task";
                asyncMethodName = methodName + "Async";
            }
            else
            {
                asyncReturnType = $"Task<{returnType}>";
                asyncMethodName = methodName + "Async";
                innerType = returnType; // For non-async methods with return value
            }

            sb.AppendLine();
            sb.AppendLine($"        [global::SharedMeta.Core.GeneratedFromMetaMethod(typeof(global::{interfaceFqn}), \"{methodName}\")]");
            sb.AppendLine($"        public async {asyncReturnType} {asyncMethodName}({parameters})");
            sb.AppendLine("        {");

            // Serialize arguments based on detected serializer
            GenerateArgumentPacking(sb, method.Parameters, paramNames, serializer);

            // Call remote entity via context's CallEntityAsync
            // Errors are thrown as exceptions by the handler
            sb.AppendLine();
            sb.AppendLine($"            var resultBytes = await _context.CallEntityAsync(");
            sb.AppendLine($"                _entityId, \"{interfaceName}\", \"{methodAlias}\", argsBytes);");

            if (innerType != null)
            {
                // Has return value - deserialize and record
                sb.AppendLine();
                GenerateResultDeserialization(sb, innerType, serializer);
                sb.AppendLine("            _context.Writer.Write(result);");
                sb.AppendLine("            return result;");
            }
            // void async - nothing to return

            sb.AppendLine("        }");
        }


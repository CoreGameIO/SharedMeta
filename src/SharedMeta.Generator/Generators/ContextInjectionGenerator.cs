        private static void GenerateEntityRecorderMethod(StringBuilder sb, IMethodSymbol method, string interfaceName, DetectedSerializer serializer)
        {
            var methodName = method.Name;
            var returnType = method.ReturnType.ToDisplayString();

            // Get method alias from MetaMethod attribute if available
            var methodAlias = methodName;
            var metaMethodAttr = method.GetAttributes().FirstOrDefault(a =>
                a.AttributeClass?.ToDisplayString() == "SharedMeta.Core.MetaMethodAttribute");
            if (metaMethodAttr != null)
            {
                var aliasArg = metaMethodAttr.NamedArguments.FirstOrDefault(a => a.Key == "Alias");
                if (!aliasArg.Value.IsNull && aliasArg.Value.Value is string alias && !string.IsNullOrEmpty(alias))
                {
                    methodAlias = alias;
                }
            }

            // Build parameter list
            var parameters = string.Join(", ", method.Parameters.Select(p => $"{p.Type.ToDisplayString()} {p.Name}"));
            var paramNames = method.Parameters.Select(p => p.Name).ToList();

            var (isAsync, innerType) = ParseReturnType(returnType);

            // Determine async method signature
            string asyncReturnType;
            string asyncMethodName;

            if (isAsync)
            {
                asyncReturnType = returnType;
                asyncMethodName = methodName;
            }
            else if (returnType == "void")
            {
                asyncReturnType = "Task";
                asyncMethodName = methodName + "Async";
            }
            else
            {
                asyncReturnType = $"Task<{returnType}>";
                asyncMethodName = methodName + "Async";
                innerType = returnType; // For non-async methods with return value
            }

            sb.AppendLine();
            sb.AppendLine($"        public async {asyncReturnType} {asyncMethodName}({parameters})");
            sb.AppendLine("        {");

            // Serialize arguments based on detected serializer
            GenerateArgumentPacking(sb, method.Parameters, paramNames, serializer);

            // Call remote entity via context's CallEntityAsync
            // Errors are thrown as exceptions by the handler
            sb.AppendLine();
            sb.AppendLine($"            var resultBytes = await _context.CallEntityAsync(");
            sb.AppendLine($"                _entityId, \"{interfaceName}\", \"{methodAlias}\", argsBytes);");

            if (innerType != null)
            {
                // Has return value - deserialize and record
                sb.AppendLine();
                GenerateResultDeserialization(sb, innerType, serializer);
                sb.AppendLine("            _context.Writer.Write(result);");
                sb.AppendLine("            return result;");
            }
            // void async - nothing to return

            sb.AppendLine("        }");
        }

        /// <summary>
        /// Generate result deserialization code based on serializer type.
        /// </summary>
        private static void GenerateResultDeserialization(StringBuilder sb, string resultType, DetectedSerializer serializer)
        {
            if (serializer == DetectedSerializer.MemoryPack)
            {
                sb.AppendLine($"            var result = MemoryPackSerializer.Deserialize<{resultType}>(resultBytes)!;");
            }
            else
            {
                sb.AppendLine($"            var result = _context.Serializer.Unpack<{resultType}>(resultBytes)!;");
            }
        }


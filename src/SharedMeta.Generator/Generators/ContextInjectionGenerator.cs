        public static string? Generate(ClassDeclarationSyntax node, INamedTypeSymbol symbol, Compilation compilation)
        {
            // Detect serializer type for code generation
            var serializer = SerializerDetector.Detect(compilation);
            // Find the attribute
            var attr = symbol.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == "SharedMeta.Core.MetaServiceImplAttribute");
            if (attr == null) return null;

            // Get constructor arguments
            if (attr.ConstructorArguments.Length < 2) return null;

            // Arg 0: Service Interface (Type)
            // Arg 1: State Type (Type)
            var stateTypeArg = attr.ConstructorArguments[1];
            var stateTypeSymbol = stateTypeArg.Value as INamedTypeSymbol;

            if (stateTypeSymbol == null) return null;

            var stateTypeName = stateTypeSymbol.ToDisplayString();

            var namespaceName = symbol.ContainingNamespace.ToDisplayString();
            var className = symbol.Name;

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Threading.Tasks;");
            sb.AppendLine("using SharedMeta.Core;");
            sb.AppendLine("using SharedMeta.Core.Transport;");
            if (serializer == DetectedSerializer.MemoryPack)
            {
                sb.AppendLine("using System.Buffers;");
                sb.AppendLine("using MemoryPack;");
            }
            sb.AppendLine($"namespace {namespaceName}");
            sb.AppendLine("{");
            sb.AppendLine($"    public partial class {className}");
            sb.AppendLine("    {");
            sb.AppendLine($"        protected MetaContext<{stateTypeName}> Context => MetaContextAccessor.Get<{stateTypeName}>();");
            sb.AppendLine();
            sb.AppendLine($"        protected {stateTypeName} State => Context.State;");

            // Typed Config accessor — if the service has a ConfigType
            var serviceInterfaceSymbol = attr.ConstructorArguments[0].Value as INamedTypeSymbol;
            string? configTypeName = null;
            if (serviceInterfaceSymbol != null)
            {
                var metaServiceAttr = serviceInterfaceSymbol.GetAttributes().FirstOrDefault(a =>
                    a.AttributeClass?.ToDisplayString() == "SharedMeta.Core.MetaServiceAttribute");
                if (metaServiceAttr != null)
                {
                    var configTypeArg = metaServiceAttr.NamedArguments.FirstOrDefault(a => a.Key == "ConfigType");
                    if (!configTypeArg.Value.IsNull && configTypeArg.Value.Value is INamedTypeSymbol configTypeSymbol)
                    {
                        configTypeName = configTypeSymbol.ToDisplayString();
                    }
                    else
                    {
                        // Check DefaultConfig flag — resolve from compilation
                        var defaultConfigArg = metaServiceAttr.NamedArguments.FirstOrDefault(a => a.Key == "DefaultConfig");
                        if (!defaultConfigArg.Value.IsNull && defaultConfigArg.Value.Value is true)
                        {
                            configTypeName = FindDefaultConfigType(compilation);
                        }
                    }
                }
            }
            if (configTypeName != null)
            {
                sb.AppendLine();
                sb.AppendLine($"        /// <summary>Static game configuration. Provided by IMetaConfigProvider on server.</summary>");
                sb.AppendLine($"        protected {configTypeName} Config => ({configTypeName})Context.Config!;");
            }

            // PatchState accessor for ServerPatch mode — only if state has ordinal attributes
            // (PatchWrapper is generated by StatePatchGenerator only for types with [Id], [Key], or [MemoryPackOrder])
            if (HasSerializationOrdinalAttributes(stateTypeSymbol))
            {
                sb.AppendLine();
                sb.AppendLine($"        /// <summary>");
                sb.AppendLine($"        /// Typed patch-tracking wrapper for State.");
                sb.AppendLine($"        /// Always available. Tracking only active when server is in ServerPatch mode.");
                sb.AppendLine($"        /// </summary>");
                sb.AppendLine($"        protected {stateTypeName}PatchWrapper PatchState");
                sb.AppendLine("        {");
                sb.AppendLine("            get");
                sb.AppendLine("            {");
                sb.AppendLine($"                if (Context.PatchWrapper is {stateTypeName}PatchWrapper existing)");
                sb.AppendLine("                    return existing;");
                sb.AppendLine($"                var wrapper = new {stateTypeName}PatchWrapper(");
                sb.AppendLine("                    Context.State, null, Context.MetaSerializer);");
                sb.AppendLine("                Context.PatchWrapper = wrapper;");
                sb.AppendLine("                return wrapper;");
                sb.AppendLine("            }");
                sb.AppendLine("        }");
            }

            // Collect entity services for generating proxy classes
            var entityServices = new List<INamedTypeSymbol>();

            // Arg 2: Params Dependencies (Optional)
            if (attr.ConstructorArguments.Length > 2)
            {
                var depsArg = attr.ConstructorArguments[2];
                if (!depsArg.IsNull && depsArg.Values.Length > 0)
                {
                    foreach (var dep in depsArg.Values)
                    {
                        var depSymbol = dep.Value as INamedTypeSymbol;
                        if (depSymbol != null)
                        {
                            // Check if this is an entity service (implements IMetaService, no [ServerMetaService])
                            if (IsEntityService(depSymbol))
                            {
                                GenerateEntityServiceGetter(sb, depSymbol);
                                entityServices.Add(depSymbol);
                            }
                            else
                            {
                                // Server service (e.g., ILobbyRequester)
                                GenerateServerServiceGetter(sb, depSymbol);
                            }
                        }
                    }
                }
            }

            sb.AppendLine("    }");

            // Generate entity caller interfaces and proxy classes
            foreach (var entityService in entityServices)
            {
                GenerateEntityCallerInterface(sb, entityService, namespaceName);
                GenerateEntityRecorderClass(sb, entityService, namespaceName, serializer);
                GenerateEntityReplayerClass(sb, entityService, namespaceName);
                GenerateLocalEntityCallerClass(sb, entityService, namespaceName, stateTypeName);
            }

            sb.AppendLine("}");

            return sb.ToString();
        }

        private static bool HasServerMetaServiceAttribute(INamedTypeSymbol symbol)
        {
            // Check if the interface has [ServerMetaService] attribute
            return symbol.GetAttributes().Any(a =>
                a.AttributeClass?.ToDisplayString() == "SharedMeta.Core.ServerMetaServiceAttribute");
        }

        private static bool IsEntityService(INamedTypeSymbol symbol)
        {
            // Entity services: implement IMetaService but don't have [ServerMetaService] attribute
            // Server services: have [ServerMetaService] attribute (may or may not implement IMetaService)
            if (HasServerMetaServiceAttribute(symbol))
                return false;

            // Check if the interface implements IMetaService
            foreach (var iface in symbol.AllInterfaces)
            {
                if (iface.ToDisplayString() == "SharedMeta.Core.IMetaService")
                    return true;
            }
            // Also check direct base
            if (symbol.ToDisplayString() == "SharedMeta.Core.IMetaService")
                return true;
            foreach (var baseType in symbol.Interfaces)
            {
                if (baseType.ToDisplayString() == "SharedMeta.Core.IMetaService")
                    return true;
            }
            return false;
        }

        /// <summary>
        /// Generate getter for entity services (cross-entity calls).
        /// Returns the async EntityCaller interface, not the original service interface.
        /// </summary>
        private static void GenerateEntityServiceGetter(StringBuilder sb, INamedTypeSymbol depSymbol)
        {
            var interfaceName = depSymbol.Name;

            // Base name: IProfileService -> ProfileService
            var baseName = interfaceName;
            if (baseName.StartsWith("I") && baseName.Length > 1 && char.IsUpper(baseName[1]))
            {
                baseName = baseName.Substring(1);
            }

            var entityCallerInterface = $"{interfaceName}EntityCaller";

            sb.AppendLine();
            sb.AppendLine($"        /// <summary>");
            sb.AppendLine($"        /// Get a proxy to call {interfaceName} on another entity.");
            sb.AppendLine($"        /// Returns async EntityCaller interface for cross-entity communication.");
            sb.AppendLine($"        /// On server: packs args and calls CallEntityAsync (EntityRecorder).");
            sb.AppendLine($"        /// On client with CrossEntityResolver: executes locally (LocalEntityCaller).");
            sb.AppendLine($"        /// On client without CrossEntityResolver: replays from recorded data (EntityReplayer).");
            sb.AppendLine($"        /// </summary>");
            sb.AppendLine($"        protected {entityCallerInterface} Get{interfaceName}(string entityId)");
            sb.AppendLine("        {");
            sb.AppendLine("            if (Context.IsServer)");
            sb.AppendLine("            {");
            sb.AppendLine($"                return new {baseName}EntityRecorder(entityId, (IServerRecordContext)Context);");
            sb.AppendLine("            }");
            sb.AppendLine("            else if (Context.CrossEntityResolver != null)");
            sb.AppendLine("            {");
            sb.AppendLine($"                return new {baseName}LocalEntityCaller(entityId, Context.CrossEntityResolver);");
            sb.AppendLine("            }");
            sb.AppendLine("            else");
            sb.AppendLine("            {");
            sb.AppendLine($"                return new {baseName}EntityReplayer((IClientReplayContext)Context);");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
        }

        /// <summary>
        /// Generate getter for server services (e.g., ILobbyRequester).
        /// Server services are singleton services resolved from DI.
        /// </summary>
        private static void GenerateServerServiceGetter(StringBuilder sb, INamedTypeSymbol depSymbol)
        {
            var fullTypeName = depSymbol.ToDisplayString();
            var interfaceName = depSymbol.Name;
            var depNamespace = depSymbol.ContainingNamespace.ToDisplayString();

            // Property name: IRandomService -> RandomService
            var propName = interfaceName;
            if (propName.StartsWith("I") && propName.Length > 1 && char.IsUpper(propName[1]))
            {
                propName = propName.Substring(1);
            }

            // Base name for wrapper classes: IRandomService -> RandomService
            var baseName = propName;

            // Cache key - use typeof()
            var cacheKey = $"typeof({fullTypeName})";

            sb.AppendLine();
            sb.AppendLine($"        protected {fullTypeName} {propName} => Get{interfaceName}();");
            sb.AppendLine();
            sb.AppendLine($"        private {fullTypeName} Get{interfaceName}()");
            sb.AppendLine("        {");
            sb.AppendLine($"            if (Context.TryGetCached({cacheKey}, out var cached))");
            sb.AppendLine($"                return ({fullTypeName})cached!;");
            sb.AppendLine();
            sb.AppendLine("            object wrapper;");
            sb.AppendLine("            if (Context.IsServer)");
            sb.AppendLine("            {");
            sb.AppendLine($"                // Server: Create Recorder wrapper");
            sb.AppendLine($"                var realImpl = Context.ResolveService<{fullTypeName}>();");
            sb.AppendLine($"                wrapper = new {depNamespace}.Server.{baseName}Recorder(realImpl, (IServerRecordContext)Context);");
            sb.AppendLine("            }");
            sb.AppendLine("            else");
            sb.AppendLine("            {");
            sb.AppendLine($"                // Client: Create Replayer wrapper");
            sb.AppendLine($"                wrapper = new {depNamespace}.Client.{baseName}Replayer((IClientReplayContext)Context);");
            sb.AppendLine("            }");
            sb.AppendLine();
            sb.AppendLine($"            Context.CacheService({cacheKey}, wrapper);");
            sb.AppendLine($"            return ({fullTypeName})wrapper;");
            sb.AppendLine("        }");
        }

        /// <summary>
        /// Generate async EntityCaller interface for cross-entity calls.
        /// Methods are async versions of the original interface methods.
        /// </summary>
        private static void GenerateEntityCallerInterface(StringBuilder sb, INamedTypeSymbol interfaceSymbol, string containingNamespace)
        {
            var interfaceName = interfaceSymbol.Name;
            var entityCallerInterface = $"{interfaceName}EntityCaller";

            sb.AppendLine();
            sb.AppendLine($"    /// <summary>");
            sb.AppendLine($"    /// Async interface for cross-entity calls to {interfaceName}.");
            sb.AppendLine($"    /// All methods are async to support inter-entity RPC.");
            sb.AppendLine($"    /// </summary>");
            sb.AppendLine($"    public interface {entityCallerInterface}");
            sb.AppendLine("    {");

            foreach (var member in interfaceSymbol.GetMembers().OfType<IMethodSymbol>())
            {
                if (member.MethodKind == MethodKind.Ordinary)
                {
                    GenerateEntityCallerInterfaceMethod(sb, member);
                }
            }

            sb.AppendLine("    }");
        }

        private static void GenerateEntityCallerInterfaceMethod(StringBuilder sb, IMethodSymbol method)
        {
            var methodName = method.Name;
            var returnType = method.ReturnType.ToDisplayString();
            var parameters = string.Join(", ", method.Parameters.Select(p => $"{p.Type.ToDisplayString()} {p.Name}"));

            var (isAsync, innerType) = ParseReturnType(returnType);

            // Generate async version of the method
            string asyncReturnType;
            string asyncMethodName;

            if (isAsync)
            {
                // Already async - keep as is
                asyncReturnType = returnType;
                asyncMethodName = methodName;
            }
            else if (returnType == "void")
            {
                // void -> Task, add Async suffix
                asyncReturnType = "Task";
                asyncMethodName = methodName + "Async";
            }
            else
            {
                // T -> Task<T>, add Async suffix
                asyncReturnType = $"Task<{returnType}>";
                asyncMethodName = methodName + "Async";
            }

            sb.AppendLine($"        {asyncReturnType} {asyncMethodName}({parameters});");
        }


        private static void GenerateLocalEntityCallerMethod(StringBuilder sb, IMethodSymbol method,
            string interfaceName, string interfaceFqn, string baseName, string targetStateType, string implNamespace)
        {
            var methodName = method.Name;
            var returnType = method.ReturnType.ToDisplayString();
            var parameters = string.Join(", ", method.Parameters.Select(p => $"{p.Type.ToDisplayString()} {p.Name}"));
            var paramNames = method.Parameters.Select(p => p.Name).ToList();
            var callArgs = string.Join(", ", paramNames);

            var (isAsync, innerType) = ParseReturnType(returnType);

            // 0.22.0+: OneWay variant for CrossOptimistic mode is a void no-op locally — the
            // server-side dispatch happens via the optimistic→server confirm flow as usual,
            // but the caller doesn't observe a result, so the local-side call body is just empty.
            // Keep the subscription gate so CrossOptimistic continues to treat unknown entities
            // as a soft-fail (no exception, no state mutation).
            if (IsNotificationMode(method))
            {
                sb.AppendLine();
                sb.AppendLine($"        [global::SharedMeta.Core.GeneratedFromMetaMethod(typeof(global::{interfaceFqn}), \"{methodName}\")]");
                sb.AppendLine($"        public void {methodName}({parameters})");
                sb.AppendLine("        {");
                sb.AppendLine("            // OneWay + CrossOptimistic: no local execution. The server-side path");
                sb.AppendLine("            // fires the cross-entity OneWay; the client observes nothing here.");
                sb.AppendLine("        }");
                return;
            }

            string asyncReturnType;
            string asyncMethodName;

            if (isAsync)
            {
                asyncReturnType = returnType;
                asyncMethodName = methodName;
            }
            else if (returnType == "void")
            {
                asyncReturnType = "Task";
                asyncMethodName = methodName + "Async";
            }
            else
            {
                asyncReturnType = $"Task<{returnType}>";
                asyncMethodName = methodName + "Async";
                innerType = returnType;
            }

            string awaitPrefix = isAsync ? "await " : "";

            // Get method alias from MetaMethod attribute if available
            var methodAlias = methodName;
            var metaMethodAttr = method.GetAttributes().FirstOrDefault(a =>
                a.AttributeClass?.ToDisplayString() == "SharedMeta.Core.MetaMethodAttribute");
            if (metaMethodAttr != null)
            {
                var aliasArg = metaMethodAttr.NamedArguments.FirstOrDefault(a => a.Key == "Alias");
                if (!aliasArg.Value.IsNull && aliasArg.Value.Value is string alias && !string.IsNullOrEmpty(alias))
                {
                    methodAlias = alias;
                }
            }

            sb.AppendLine();
            sb.AppendLine($"        [global::SharedMeta.Core.GeneratedFromMetaMethod(typeof(global::{interfaceFqn}), \"{methodName}\")]");
            sb.AppendLine($"        public {asyncReturnType} {asyncMethodName}({parameters})");
            sb.AppendLine("        {");

            // Check subscription synchronously — no network calls allowed.
            // If not subscribed, silently return default. The CrossOptimistic method
            // continues execution — other cross-entity calls to subscribed entities still work.
            sb.AppendLine("            if (!_resolver.IsSubscribed(_entityId))");
            if (innerType != null)
            {
                sb.AppendLine($"                return Task.FromResult(default({innerType})!);");
            }
            else
            {
                sb.AppendLine("                return Task.CompletedTask;");
            }
            sb.AppendLine($"            var state = ({targetStateType})_resolver.GetEntityState(_entityId);");
            sb.AppendLine();

            // Save and set context (inherit ServerTimeTicks from parent for deterministic time)
            sb.AppendLine("            var prevCtx = MetaContextAccessor.Current;");
            sb.AppendLine($"            var ctx = new CrossOptimisticMetaContext<{targetStateType}>(state);");
            sb.AppendLine("            ctx.CrossEntityResolver = _resolver;");
            sb.AppendLine("            ctx.ServerTimeTicks = prevCtx?.ServerTimeTicks ?? 0;");
            sb.AppendLine("            ctx.Log = prevCtx?.Log ?? SharedMeta.Core.Logging.NullMetaLogger.Instance;");
            sb.AppendLine("            ctx.Config = _resolver.GetEntityConfig(_entityId);");
            sb.AppendLine("            MetaContextAccessor.Current = ctx;");
            sb.AppendLine("            try");
            sb.AppendLine("            {");
            sb.AppendLine($"                var service = new {implNamespace}.{baseName}() {{ Context = ctx }};");

            if (innerType != null)
            {
                if (isAsync)
                {
                    // Service method returns Task<T> — call and extract result synchronously.
                    // All cross-entity calls within complete synchronously (LocalEntityCaller/EntityReplayer),
                    // so the Task is guaranteed to be completed.
                    sb.AppendLine($"                var task = service.{methodName}({callArgs});");
                    sb.AppendLine($"                var result = task.GetAwaiter().GetResult();");
                }
                else
                {
                    sb.AppendLine($"                var result = service.{methodName}({callArgs});");
                }
                sb.AppendLine($"                _resolver.RecordCrossEntityResult(_entityId, \"{interfaceName}\", \"{methodAlias}\", result);");
                sb.AppendLine($"                return Task.FromResult(result);");
            }
            else
            {
                if (isAsync)
                {
                    sb.AppendLine($"                service.{methodName}({callArgs}).GetAwaiter().GetResult();");
                }
                else
                {
                    sb.AppendLine($"                service.{methodName}({callArgs});");
                }
                sb.AppendLine($"                _resolver.RecordCrossEntityResult(_entityId, \"{interfaceName}\", \"{methodAlias}\", null);");
                sb.AppendLine("                return Task.CompletedTask;");
            }

            sb.AppendLine("            }");
            sb.AppendLine("            finally");
            sb.AppendLine("            {");
            sb.AppendLine("                MetaContextAccessor.Current = prevCtx;");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
        }

        /// <summary>
        /// Generate argument packing code based on serializer type.
        /// </summary>
        private static void GenerateArgumentPacking(
            StringBuilder sb,
            System.Collections.Immutable.ImmutableArray<IParameterSymbol> parameters,
            List<string> paramNames,
            DetectedSerializer serializer)
        {
            if (paramNames.Count == 0)
            {
                sb.AppendLine("            var argsBytes = Array.Empty<byte>();");
                return;
            }

            if (serializer == DetectedSerializer.MemoryPack)
            {
                // MemoryPack: use MemoryPackSerializer for direct serialization
                if (paramNames.Count == 1)
                {
                    sb.AppendLine($"            var argsBytes = MemoryPackSerializer.Serialize({paramNames[0]});");
                }
                else
                {
                    // Multiple parameters: serialize to ArrayBufferWriter sequentially
                    sb.AppendLine("            var buffer = new ArrayBufferWriter<byte>();");
                    foreach (var paramName in paramNames)
                    {
                        sb.AppendLine($"            MemoryPackSerializer.Serialize(buffer, {paramName});");
                    }
                    sb.AppendLine("            var argsBytes = buffer.WrittenSpan.ToArray();");
                }
            }
            else
            {
                // Generic: always use IPayloadWriter for consistent length-prefixed format.
                // Server dispatcher reads with CreateReader() which expects length-prefixed data.
                sb.AppendLine("            using var writer = _context.Serializer.CreateWriter();");
                foreach (var paramName in paramNames)
                {
                    sb.AppendLine($"            writer.Write({paramName});");
                }
                sb.AppendLine("            var argsBytes = writer.Complete();");
            }
        }

        /// <summary>
        /// Parse async return type. Returns (isAsync, innerType).
        /// Task -> (true, null), Task&lt;bool&gt; -> (true, "bool"), int -> (false, "int")
        /// </summary>
        private static (bool isAsync, string? innerType) ParseReturnType(string returnType)
        {
            if (returnType == "System.Threading.Tasks.Task" || returnType == "Task")
                return (true, null);

            var match = Regex.Match(returnType, @"^(?:System\.Threading\.Tasks\.)?Task<(.+)>$");
            if (match.Success)
                return (true, match.Groups[1].Value);

            if (returnType == "void")
                return (false, null);

            return (false, returnType);
        }

        /// <summary>
        /// Check if a type has properties with serialization ordinal attributes
        /// ([Id], [Key], [MemoryPackOrder]) — same set StatePatchGenerator uses.
        /// </summary>
        private static string? FindDefaultConfigType(Compilation compilation)
        {
            // Search source types
            var result = FindDefaultConfigTypeInNamespace(compilation.Assembly.GlobalNamespace);
            if (result != null) return result;

            // Search referenced assemblies
            foreach (var reference in compilation.References)
            {
                var assemblySymbol = compilation.GetAssemblyOrModuleSymbol(reference) as IAssemblySymbol;
                if (assemblySymbol == null) continue;
                var name = assemblySymbol.Name;
                if (name.StartsWith("System") || name.StartsWith("Microsoft") ||
                    name.StartsWith("netstandard") || name.StartsWith("SharedMeta"))
                    continue;

                result = FindDefaultConfigTypeInNamespace(assemblySymbol.GlobalNamespace);
                if (result != null) return result;
            }
            return null;
        }

        /// <summary>
        /// 0.20.0: Read the dep entity-service's TState directly from
        /// <c>[MetaService(StateType = typeof(...))]</c> on the interface symbol — no compilation
        /// scan, attribute is already on the symbol. Every entity service is bound to a TState
        /// (no entity service can exist without one — that's where it lives), so this lookup
        /// must succeed for any well-formed entity service. Returns null only when the attribute
        /// is missing or doesn't set <c>StateType</c> — caller emits a generator error.
        /// </summary>
        private static string? ReadDepStateType(INamedTypeSymbol depInterface)
        {
            var metaServiceAttr = depInterface.GetAttributes().FirstOrDefault(a =>
                a.AttributeClass?.ToDisplayString() == "SharedMeta.Core.MetaServiceAttribute");
            if (metaServiceAttr == null) return null;
            var stateTypeArg = metaServiceAttr.NamedArguments.FirstOrDefault(a => a.Key == "StateType");
            if (stateTypeArg.Value.Value is INamedTypeSymbol stateType)
                return stateType.ToDisplayString();
            return null;
        }

        private static string? FindDefaultConfigTypeInNamespace(INamespaceSymbol ns)
        {
            foreach (var type in ns.GetTypeMembers())
            {
                var attr = type.GetAttributes().FirstOrDefault(a =>
                    a.AttributeClass?.ToDisplayString() == "SharedMeta.Core.MetaConfigAttribute");
                if (attr != null)
                {
                    var defaultArg = attr.NamedArguments.FirstOrDefault(a => a.Key == "Default");
                    if (!defaultArg.Value.IsNull && defaultArg.Value.Value is true)
                        return type.ToDisplayString();
                }
            }
            foreach (var childNs in ns.GetNamespaceMembers())
            {
                var result = FindDefaultConfigTypeInNamespace(childNs);
                if (result != null) return result;
            }
            return null;
        }

        private static bool HasSerializationOrdinalAttributes(INamedTypeSymbol type)
        {
            return type.GetMembers().OfType<IPropertySymbol>().Any(p =>
                p.DeclaredAccessibility == Accessibility.Public &&
                !p.IsStatic &&
                p.GetMethod != null && p.SetMethod != null &&
                p.GetAttributes().Any(a =>
                {
                    var name = a.AttributeClass?.Name;
                    var ns = a.AttributeClass?.ContainingNamespace.ToDisplayString();
                    return (name == "IdAttribute" && ns == "Orleans") ||
                           (name == "KeyAttribute" && ns == "MessagePack") ||
                           (name == "MemoryPackOrderAttribute" && ns == "MemoryPack");
                }));
        }
